"""Check independent quality rules and hit provenance in candidate exports."""

import csv
import gzip
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).parent))
import swh_p4_candidate_quality as QUALITY


class CandidateQualityTests(unittest.TestCase):
    def test_quality_thresholds_and_encoding(self):
        good = b"#include <core.p4>\nstruct H { bit<8> x; }\n"
        result = QUALITY.inspect_quality(QUALITY.git_blob_sha1(good), good)
        self.assertEqual(result["quality_status"], "pass")
        self.assertEqual(result["quality_encoding"], "utf-8")
        self.assertEqual(result["line_count"], 2)
        bad = b"// generated by tool\n" + b"a" * 1001 + b"\n"
        result = QUALITY.inspect_quality(QUALITY.git_blob_sha1(bad), bad)
        self.assertEqual(result["quality_status"], "excluded")
        self.assertIn("generated_header", result["quality_flags"])
        self.assertIn("very_long_line", result["quality_flags"])
        self.assertEqual(QUALITY.inspect_quality(QUALITY.git_blob_sha1(good), b"changed")[
            "quality_status"], "unknown")
        self.assertEqual(QUALITY.inspect_quality(QUALITY.git_blob_sha1(b"\xff"), b"\xff")[
            "quality_status"], "unknown")
        utf16_be = "struct H {}\n".encode("utf-16")
        result = QUALITY.inspect_quality(QUALITY.git_blob_sha1(utf16_be), utf16_be)
        self.assertEqual(result["quality_status"], "pass")

    def test_encoded_ratio_and_diagnostic_only_metrics(self):
        encoded = b"const string x = \"" + b"A" * 1050 + b"\";\n"
        result = QUALITY.inspect_quality(QUALITY.git_blob_sha1(encoded), encoded)
        self.assertIn("encoded_data", result["quality_flags"])
        self.assertGreater(result["encoded_data_ratio"], 0.5)
        repeated = b"bit<8> x;\n" * 40
        result = QUALITY.inspect_quality(QUALITY.git_blob_sha1(repeated), repeated)
        self.assertEqual(result["quality_status"], "pass")
        self.assertGreater(result["duplicate_nonempty_line_ratio"], 0.9)

    def test_csv_split_preserves_every_hit(self):
        good = b"struct H {}\n"
        bad = b"// generated by tool\nstruct H {}\n"
        good_id, bad_id = QUALITY.git_blob_sha1(good), QUALITY.git_blob_sha1(bad)
        annotations = {content_id: QUALITY.inspect_quality(content_id, data)
                       for content_id, data in ((good_id, good), (bad_id, bad))}
        fields = ["content_id", "directory_id", "name", "source_csv", "source_row",
                  "source_csv_index", "discovery_disposition", "provenance"]
        rows = []
        for index, (content_id, directory_id) in enumerate(
                ((good_id, "a"), (good_id, "b"), (bad_id, "b")), 1):
            rows.append(dict(zip(fields, (content_id, directory_id, "x,quoted.p4", "input.csv",
                                          str(index), "0", "p4_16_candidate", "line1\nline2"))))
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "source.csv"
            with source.open("w", encoding="utf-8", newline="") as stream:
                writer = csv.DictWriter(stream, fieldnames=fields)
                writer.writeheader()
                writer.writerows(rows)
            result = QUALITY.transform_shard(source, root / "output", 0, annotations)
            self.assertEqual(result["counts"], {"pass": 2, "excluded": 1})
            self.assertEqual(result["rows"], 3)
            for entry in result["files"]:
                with gzip.open(entry["path"], "rt", encoding="utf-8", newline="") as stream:
                    saved = list(csv.DictReader(stream))
                original = rows[:2] if entry["group"] == "quality_pass_csv" else (
                    rows[2:] if entry["group"] == "quality_excluded_csv" else [])
                self.assertEqual([{field: row[field] for field in fields} for row in saved], original)


if __name__ == "__main__":
    unittest.main()
