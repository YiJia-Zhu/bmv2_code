#!/usr/bin/env python3
"""Normalize collected P4 repositories into provenance-preserving JSONL.

Raw repositories are never modified.  The normalized output contains one JSON
record per accepted source/context file, with content, provenance, language,
architecture hints, license hints and duplicate information.  Filtered files
are recorded separately so decisions remain auditable.
"""

import argparse
import datetime as dt
import hashlib
import json
import re
import sys
from pathlib import Path


DATA_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RAW_ROOT = DATA_ROOT / "raw" / "repositories"
DEFAULT_OUTPUT_ROOT = DATA_ROOT / "normalized"
P4_EXTENSIONS = {".p4", ".p4i", ".p4_14", ".p4_16"}
TEST_EXTENSIONS = {".stf", ".pcap", ".pcapng"}
CONTEXT_EXTENSIONS = {
    ".py",
    ".json",
    ".jsonpb",
    ".txtpb",
    ".yaml",
    ".yml",
    ".toml",
    ".sh",
    ".mk",
    ".md",
    ".rst",
    ".txt",
    ".cfg",
    ".ini",
}
SUPPORT_EXTENSIONS = {".c", ".cc", ".cpp", ".h", ".hh", ".hpp"}
SPECIAL_FILENAMES = {"Makefile", "Dockerfile", "BUILD", "BUILD.bazel", "CMakeLists.txt"}
SKIP_PARTS = {
    ".git",
    "__pycache__",
    "node_modules",
    "build",
    "out",
    "dist",
    "bazel-bin",
    "bazel-out",
    "p4_16_samples_outputs",
    "p4_16_errors_outputs",
    "p4_14_samples_outputs",
    "p4_14_errors_outputs",
}
AUTOGENERATED_MARKERS = (
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "generated automatically",
    "this file is generated",
)


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw-root", type=Path, default=DEFAULT_RAW_ROOT)
    parser.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT_ROOT)
    parser.add_argument("--max-bytes", type=int, default=500 * 1024)
    parser.add_argument("--max-lines", type=int, default=100000)
    parser.add_argument(
        "--include-supporting",
        action="store_true",
        default=True,
        help="include control-plane, test, documentation and small support files",
    )
    return parser.parse_args()


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def sha256_text(text):
    return sha256_bytes(text.encode("utf-8"))


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def skip_path(path):
    return any(part in SKIP_PARTS for part in path.parts)


def file_kind(path):
    if path.name in SPECIAL_FILENAMES:
        return "build_or_project_metadata"
    suffix = path.suffix.lower()
    if suffix in P4_EXTENSIONS:
        return "p4_source"
    if suffix in TEST_EXTENSIONS:
        return "test_vector_or_capture"
    if suffix in CONTEXT_EXTENSIONS:
        return "project_context"
    if suffix in SUPPORT_EXTENSIONS:
        return "supporting_source"
    return None


def p4_version(text, path):
    p4_14 = bool(
        re.search(r"\b(header_type|field_list|field_list_calculation|parser\s*\{)", text)
    )
    p4_16 = bool(
        re.search(
            r"\b(package\s+\w+\s*\(|header\s+\w+\s*\{|struct\s+\w+\s*\{|control\s+\w+\s*\(|parser\s+\w+\s*\()",
            text,
        )
    ) or "v1model.p4" in text or "psa.p4" in text
    if p4_14 and p4_16:
        return "mixed_or_uncertain"
    if p4_16:
        return "p4_16"
    if p4_14:
        return "p4_14"
    if "p4_14" in str(path).lower():
        return "p4_14_path_hint"
    return "unknown"


def architecture_hint(text, path):
    value = (str(path) + "\n" + text).lower()
    for token, architecture in (
        ("v1model.p4", "v1model"),
        ("v1model", "v1model"),
        ("psa.p4", "psa"),
        ("tna", "tna/tofino"),
        ("tofino", "tna/tofino"),
        ("ebpf", "ebpf"),
        ("pna", "pna"),
        ("dpdk", "dpdk"),
        ("xilinx", "xilinx/vitis"),
        ("vitis", "xilinx/vitis"),
    ):
        if token in value:
            return architecture
    return "unknown"


def license_hint(repo_dir, relative_path, text):
    header = text[:4000]
    match = re.search(r"SPDX-License-Identifier:\s*([^\s*]+)", header, re.I)
    if match:
        return match.group(1)
    for parent in [repo_dir / relative_path.parent, repo_dir]:
        for name in ("LICENSE", "LICENSE.md", "COPYING", "NOTICE"):
            candidate = parent / name
            if candidate.is_file():
                return "repository-file:{}".format(name)
    return "unknown"


def is_probably_p4(text):
    return bool(
        re.search(
            r"\b(header|parser|control|action|table|extern|package|bit\s*<\s*\d+>)\b",
            text,
        )
    )


def quality_rejection(text, path, max_bytes, max_lines):
    raw = text.encode("utf-8")
    if not text.strip():
        return "empty"
    if len(raw) > max_bytes:
        return "larger_than_max_bytes"
    lines = text.splitlines()
    if len(lines) > max_lines:
        return "more_than_max_lines"
    first_lines = "\n".join(lines[:5]).lower()
    if any(marker in first_lines for marker in AUTOGENERATED_MARKERS):
        return "autogenerated_marker"
    if path.suffix.lower() in P4_EXTENSIONS and not is_probably_p4(text):
        return "not_probably_p4"
    if path.suffix.lower() in P4_EXTENSIONS:
        long_line = max((len(line) for line in lines), default=0)
        if long_line > 100000:
            return "encoded_or_data_like_long_line"
    return None


def normalize_hash_text(text):
    return re.sub(r"\s+", " ", text).strip()


def source_role(repo_id, relative_path, kind):
    value = str(relative_path).lower()
    if kind == "p4_source":
        if "error" in value or "err" in value:
            return "compiler_error_seed"
        if "solution" in value:
            return "reference_solution_seed"
        if "exercise" in value or "tutorial" in value or "example" in value:
            return "task_seed"
        return "p4_source"
    if kind == "test_vector_or_capture":
        return "test_vector"
    if kind == "project_context":
        if value.endswith(".py") or value.endswith(".json") or "runtime" in value:
            return "control_or_runner_context"
        return "documentation_or_project_context"
    if kind == "build_or_project_metadata":
        return "build_context"
    return "supporting_source"


def main():
    args = parse_args()
    raw_root = args.raw_root.resolve()
    output_root = args.output_root.resolve()
    output_root.mkdir(parents=True, exist_ok=True)
    all_path = output_root / "all_records.jsonl"
    accepted_path = output_root / "accepted_records.jsonl"
    p4_path = output_root / "p4_code.jsonl"
    filtered_path = output_root / "filtered_records.jsonl"
    stats = {
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "raw_root": str(raw_root),
        "max_bytes": args.max_bytes,
        "repositories": 0,
        "files_seen": 0,
        "accepted": 0,
        "filtered": 0,
        "unique_content": 0,
        "by_kind": {},
        "by_p4_version": {},
        "by_architecture": {},
        "by_repository": {},
    }
    seen_content = {}
    seen_normalized = {}
    accepted = []
    all_records = []
    filtered = []

    repo_dirs = sorted(
        path
        for path in raw_root.iterdir()
        if path.is_dir() and not path.name.endswith(".partial") and (path / "collection.json").is_file()
    ) if raw_root.is_dir() else []
    stats["repositories"] = len(repo_dirs)

    for repo_dir in repo_dirs:
        metadata = read_json(repo_dir / "collection.json")
        repo_id = metadata.get("id", repo_dir.name)
        print("[normalize] {}".format(repo_id), flush=True)
        repo_stats = stats["by_repository"].setdefault(repo_id, {"seen": 0, "accepted": 0})
        for path in sorted(repo_dir.rglob("*")):
            if not path.is_file() or path.name in {"collection.json", "DOWNLOAD_SOURCE.json"}:
                continue
            relative = path.relative_to(repo_dir)
            if skip_path(relative):
                continue
            kind = file_kind(path)
            if kind is None:
                continue
            stats["files_seen"] += 1
            repo_stats["seen"] += 1
            try:
                data = path.read_bytes()
                text = data.decode("utf-8")
            except (OSError, UnicodeDecodeError):
                record = {
                    "record_id": "{}:{}".format(repo_id, relative),
                    "source_repo": metadata.get("repository", repo_id),
                    "source_commit": metadata.get("commit"),
                    "source_path": str(relative),
                    "record_kind": kind,
                    "status": "filtered",
                    "filter_reason": "binary_or_non_utf8",
                }
                filtered.append(record)
                continue

            reason = quality_rejection(text, path, args.max_bytes, args.max_lines)
            record_id = "{}:{}".format(repo_id, relative)
            base_record = {
                "record_id": record_id,
                "source_repo_id": repo_id,
                "source_repo": metadata.get("repository", repo_id),
                "source_url": metadata.get("url"),
                "source_commit": metadata.get("commit"),
                "source_branch": metadata.get("branch"),
                "source_path": str(relative),
                "record_kind": kind,
                "source_role": source_role(repo_id, relative, kind),
                "license_hint": license_hint(repo_dir, relative, text),
                "size_bytes": len(data),
                "line_count": len(text.splitlines()),
                "sha256": sha256_bytes(data),
                "normalized_sha256": sha256_text(normalize_hash_text(text)),
            }
            if kind == "p4_source":
                base_record["language"] = p4_version(text, relative)
                base_record["architecture"] = architecture_hint(text, relative)
                base_record["is_probably_p4"] = is_probably_p4(text)
            if reason:
                base_record.update({"status": "filtered", "filter_reason": reason})
                filtered.append(base_record)
                continue

            content_hash = base_record["sha256"]
            normalized_hash = base_record["normalized_sha256"]
            duplicate_of = seen_content.get(content_hash)
            if duplicate_of is None:
                duplicate_of = seen_normalized.get(normalized_hash)
            base_record.update({"status": "accepted", "duplicate_of": duplicate_of, "content": text})
            all_records.append(base_record)
            if duplicate_of is None:
                seen_content[content_hash] = record_id
                seen_normalized[normalized_hash] = record_id
                accepted.append(base_record)
                repo_stats["accepted"] += 1
                stats["unique_content"] += 1
            else:
                base_record["status"] = "accepted_duplicate"
            stats["accepted"] += 1
            stats["by_kind"][kind] = stats["by_kind"].get(kind, 0) + 1
            if kind == "p4_source":
                version = base_record["language"]
                arch = base_record["architecture"]
                stats["by_p4_version"][version] = stats["by_p4_version"].get(version, 0) + 1
                stats["by_architecture"][arch] = stats["by_architecture"].get(arch, 0) + 1

        stats["filtered"] = len(filtered)

    def write_records(path, records):
        with path.open("w", encoding="utf-8") as handle:
            for record in records:
                handle.write(json.dumps(record, ensure_ascii=False) + "\n")

    write_records(all_path, all_records)
    write_records(accepted_path, accepted)
    write_records(p4_path, [record for record in accepted if record["record_kind"] == "p4_source"])
    write_records(filtered_path, filtered)
    write_json(output_root / "stats.json", stats)
    print(json.dumps(stats, ensure_ascii=False, indent=2))
    print("normalized output: {}".format(output_root))
    return 0


if __name__ == "__main__":
    sys.exit(main())
