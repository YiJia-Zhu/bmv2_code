RULE_VERSION = "p4-content-screen-v1"
SHA1_RE = re.compile(r"^[0-9a-f]{40}$")
P4_16_RULES = {
    "core_include": re.compile(r'^\s*#\s*include\s*[<"](?:core|v1model|psa|pna)\.p4[>"]', re.M),
    "packet_in_parser": re.compile(r"\bparser\s+\w+\s*\([^;{}]*\bpacket_in\b", re.S),
    "struct_definition": re.compile(r"\bstruct\s+\w+\s*\{"),
    "v1switch": re.compile(r"\bV1Switch\s*\("),
    "psa_switch": re.compile(r"\bPSA_Switch\s*\("),
}
P4_14_RULES = {
    "header_type": re.compile(r"\bheader_type\s+\w+\s*\{"),
    "field_list": re.compile(r"\bfield_list(?:_calculation)?\s+\w+\s*\{"),
    "fields_block": re.compile(r"\bfields\s*\{"),
    "legacy_parser": re.compile(r"\bparser\s+start\s*\{[^}]*\breturn\b", re.S),
}
LFS_POINTER = re.compile(
    r"\Aversion https://git-lfs\.github\.com/spec/v1\n"
    r"oid sha256:[0-9a-f]{64}\nsize [0-9]+\n?\Z"
)
GENERATED = re.compile(r"(?:auto[- ]generated|generated by|do not edit)", re.I)
ENCODED = re.compile(r"[A-Za-z0-9+/=]{1025,}|(?:\\x[0-9a-fA-F]{2}){256,}|(?:\\u[0-9a-fA-F]{4}){256,}")
LOG = logging.getLogger("swh_p4_screen")


def utc_now():
    return dt.datetime.now(dt.timezone.utc).isoformat()


def git_blob_sha1(data):
    return hashlib.sha1(b"blob " + str(len(data)).encode("ascii") + b"\0" + data).hexdigest()


def code_without_comments_or_strings(source, keep_strings=False):
    """Preserve positions/newlines while excluding comments and most strings."""
    out = []
    state = "code"
    index = 0
    while index < len(source):
        char = source[index]
        next_char = source[index + 1] if index + 1 < len(source) else ""
        if state == "code":
            if char == "/" and next_char == "/":
                out.extend("  ")
                index += 2
                state = "line_comment"
                continue
            if char == "/" and next_char == "*":
                out.extend("  ")
                index += 2
                state = "block_comment"
                continue
            if char in ('"', "'"):
                out.append(char if keep_strings else " ")
                state = char
            else:
                out.append(char)
        elif state == "line_comment":
            out.append("\n" if char == "\n" else " ")
            if char == "\n":
                state = "code"
        elif state == "block_comment":
            if char == "*" and next_char == "/":
                out.extend("  ")
                index += 2
                state = "code"
                continue
            out.append("\n" if char == "\n" else " ")
        else:
            if char == "\\" and next_char:
                out.extend(source[index:index + 2] if keep_strings else "  ")
                index += 2
                continue
            out.append(char if keep_strings else ("\n" if char == "\n" else " "))
            if char == state:
                state = "code"
        index += 1
    return "".join(out)


def inspect_content(content_id, data):
    result = {
        "content_id": content_id,
        "rule_version": RULE_VERSION,
        "raw_bytes": len(data),
        "sha1_git_verified": git_blob_sha1(data) == content_id,
        "version_status": "uninspected",
        "quality_status": "unknown",
        "quality_flags": [],
    }
    if not result["sha1_git_verified"]:
        result["fetch_status"] = "hash_mismatch"
        return result
    if not data:
        result.update(version_status="non_source", quality_status="excluded", quality_flags=["empty"])
        return result
    try:
        if data.startswith((b"\xff\xfe", b"\xfe\xff")):
            source = data.decode("utf-16")
            encoding = "utf-16"
        else:
            source = data.decode("utf-8-sig")
            encoding = "utf-8"
    except UnicodeDecodeError:
        result["decode_status"] = "unsupported_encoding"
        return result
    result["encoding"] = encoding
    if "\x00" in source:
        result.update(version_status="non_source", quality_status="excluded", quality_flags=["nul_character"])
        return result
    if LFS_POINTER.fullmatch(source):
        result.update(version_status="non_source", quality_status="excluded", quality_flags=["git_lfs_pointer"])
        return result
    code = code_without_comments_or_strings(source)
    include_source = code_without_comments_or_strings(source, keep_strings=True)
    positives = [name for name, rule in P4_16_RULES.items()
                 if rule.search(include_source if name == "core_include" else code)]
    negatives = [name for name, rule in P4_14_RULES.items() if rule.search(code)]
    if positives and negatives:
        version = "mixed_or_conflicted"
    elif positives:
        version = "p4_16_likely"
    elif negatives:
        version = "p4_14_likely"
    else:
        version = "unknown"
    lines = source.splitlines()
    if not lines and source:
        lines = [source]
    lengths = [len(line) for line in lines]
    characters = sum(lengths)
    letters = sum(char.isalpha() for line in lines for char in line)
    average = characters / len(lines) if lines else 0.0
    longest = max(lengths, default=0)
    letter_ratio = letters / characters if characters else 0.0
    flags = []
    if len(lines) > 100000:
        flags.append("too_many_lines")
    if average > 100:
        flags.append("long_average_line")
    if longest > 1000:
        flags.append("very_long_line")
    if letter_ratio < 0.25:
        flags.append("low_letter_ratio")
    if GENERATED.search("\n".join(lines[:5])):
        flags.append("generated_header")
    encoded_matches = list(ENCODED.finditer(source))
    if encoded_matches:
        flags.append("encoded_data")
    result.update(
        version_status=version,
        positive_evidence=positives,
        negative_evidence=negatives,
        line_count=len(lines),
        average_line_length=average,
        longest_line_length=longest,
        letter_ratio=letter_ratio,
        quality_flags=flags,
        quality_status="excluded" if flags else "pass",
    )
    return result


def fetch_content(content_id, api_root, timeout, max_bytes, retries, token):
    url = api_root.rstrip("/") + "/content/sha1_git:" + content_id + "/raw/"
    headers = {"User-Agent": "bmv2-swh-p4-content-screen/1.0", "Accept": "*/*"}
    if token:
        headers["Authorization"] = "Bearer " + token
    for attempt in range(retries + 1):
        try:
            request = urllib.request.Request(url, headers=headers)
            with urllib.request.urlopen(request, timeout=timeout) as response:
                data = response.read(max_bytes + 1)
            if len(data) > max_bytes:
                return None, {"fetch_status": "too_large", "bytes_read": len(data)}
            return data, {"fetch_status": "fetched", "bytes_read": len(data)}
        except urllib.error.HTTPError as exc:
            status = exc.code
            retry_after = exc.headers.get("Retry-After")
            if status not in (408, 425, 429, 500, 502, 503, 504) or attempt == retries:
                return None, {"fetch_status": "http_error", "http_status": status}
            delay = float(retry_after) if retry_after and retry_after.isdigit() else min(30, 2 ** attempt)
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            if attempt == retries:
                return None, {"fetch_status": "network_error", "error_type": type(exc).__name__}
            delay = min(30, 2 ** attempt)
        time.sleep(delay)
    raise AssertionError("unreachable")


def parse_s3_uri(uri):
    parsed = urlparse(uri)
    if parsed.scheme != "s3" or not parsed.netloc or not parsed.path.strip("/"):
        raise ValueError("expected s3://bucket/prefix URI")
    return parsed.netloc, parsed.path.lstrip("/").rstrip("/")


def load_content_ids(s3, input_uri):
    return load_content_ids_cached(s3, input_uri, None)


def load_content_ids_cached(s3, input_uri, index_cache_dir):
    import pyarrow.parquet as parquet

    bucket, prefix = parse_s3_uri(input_uri)
    cache_root = None
    if index_cache_dir is not None:
        cache_root = index_cache_dir / hashlib.sha256(input_uri.encode("utf-8")).hexdigest()[:16]
        cache_root.mkdir(parents=True, exist_ok=True)
    ids = set()
    parts = 0
    for page in s3.get_paginator("list_objects_v2").paginate(Bucket=bucket, Prefix=prefix + "/"):
        for item in page.get("Contents", []):
            key = item["Key"]
            if not key.endswith(".parquet"):
                continue
            cache_path = cache_root / key.rsplit("/", 1)[-1] if cache_root else None
            if cache_path and cache_path.exists() and cache_path.stat().st_size == item.get("Size"):
                payload = cache_path.read_bytes()
                source = "cache"
            else:
                with s3.get_object(Bucket=bucket, Key=key)["Body"] as body:
                    payload = body.read()
                source = "s3"
            table = parquet.read_table(io.BytesIO(payload), columns=["content_id"],
                                       use_threads=False)
            if cache_path and source == "s3":
                temporary = cache_path.with_suffix(".tmp")
                temporary.write_bytes(payload)
                os.replace(str(temporary), str(cache_path))
            ids.update(table.column("content_id").to_pylist())
            parts += 1
            LOG.info("index_part=%d source=%s ids_so_far=%d", parts, source, len(ids))
    if not ids or not all(isinstance(value, str) and SHA1_RE.fullmatch(value) for value in ids):
        raise RuntimeError("input contained no valid content IDs")
    return sorted(ids)


def load_sha1_map(s3, input_uri, cache_dir=None, workers=1):
    import pyarrow.parquet as parquet

    bucket, prefix = parse_s3_uri(input_uri)
    cache_root = None
    if cache_dir is not None:
        cache_root = cache_dir / hashlib.sha256(input_uri.encode("utf-8")).hexdigest()[:16]
        cache_root.mkdir(parents=True, exist_ok=True)
    mapping = {}
    items = []
    for page in s3.get_paginator("list_objects_v2").paginate(Bucket=bucket, Prefix=prefix + "/"):
        for item in page.get("Contents", []):
            if item["Key"].endswith(".parquet"):
                items.append(item)

    def read_part(item):
        key = item["Key"]
        cache_path = None
        if cache_root is not None:
            cache_path = cache_root / hashlib.sha256(key.encode("utf-8")).hexdigest()
        if cache_path and cache_path.exists() and cache_path.stat().st_size == item.get("Size"):
            payload = cache_path.read_bytes()
            source = "cache"
        else:
            with s3.get_object(Bucket=bucket, Key=key)["Body"] as body:
                payload = body.read()
            source = "s3"
        table = parquet.read_table(io.BytesIO(payload), columns=["content_id", "sha1"],
                                   use_threads=False)
        if cache_path and source == "s3":
            temporary = cache_path.with_suffix(".tmp")
            temporary.write_bytes(payload)
            os.replace(str(temporary), str(cache_path))
        return (key, source, list(zip(table.column("content_id").to_pylist(),
                                      table.column("sha1").to_pylist())))

    with ThreadPoolExecutor(max_workers=workers) as executor:
        futures = {executor.submit(read_part, item): item["Key"] for item in items}
        for number, future in enumerate(as_completed(futures), 1):
            key, source, pairs = future.result()
            for content_id, sha1 in pairs:
                if not (isinstance(content_id, str) and SHA1_RE.fullmatch(content_id)
                        and isinstance(sha1, str) and SHA1_RE.fullmatch(sha1)):
                    raise RuntimeError("invalid content hash mapping in " + key)
                if content_id in mapping and mapping[content_id] != sha1:
                    raise RuntimeError("ambiguous raw SHA-1 for {}".format(content_id))
                mapping[content_id] = sha1
            LOG.info("hash_map_part=%d/%d source=%s mapped_ids_so_far=%d",
                     number, len(items), source, len(mapping))
    return mapping


def fetch_content_s3(s3, content_id, sha1, max_bytes):
    from botocore.exceptions import (ClientError, EndpointConnectionError, ReadTimeoutError,
                                     ResponseStreamingError, ConnectionClosedError,
                                     IncompleteReadError, SSLError)

    try:
        response = s3.get_object(Bucket="softwareheritage", Key="content/" + sha1)
        with response["Body"] as body:
            with gzip.GzipFile(fileobj=body) as uncompressed:
                data = uncompressed.read(max_bytes + 1)
        if len(data) > max_bytes:
            return None, {"fetch_status": "too_large", "bytes_read": len(data)}
        if hashlib.sha1(data).hexdigest() != sha1 or git_blob_sha1(data) != content_id:
            return None, {"fetch_status": "hash_mismatch", "bytes_read": len(data)}
        return data, {"fetch_status": "fetched", "bytes_read": len(data),
                      "compressed_bytes": response.get("ContentLength")}
    except ClientError as exc:
        code = exc.response.get("Error", {}).get("Code", "unknown")
        return None, {"fetch_status": "s3_error", "s3_error_code": code}
    except (EndpointConnectionError, ReadTimeoutError, ResponseStreamingError,
            ConnectionClosedError, IncompleteReadError, SSLError):
        return None, {"fetch_status": "network_error"}
    except (gzip.BadGzipFile, EOFError, OSError, zlib.error):
        return None, {"fetch_status": "decompression_error"}


def write_batch(s3, rows, output_dir, s3_output_uri, batch_number):
    filename = "batch-{:05d}.jsonl".format(batch_number)
    path = output_dir / filename
    payload = "".join(json.dumps(row, sort_keys=True, ensure_ascii=False) + "\n" for row in rows).encode("utf-8")
    temporary = path.with_suffix(".tmp")
    with temporary.open("wb") as handle:
        handle.write(payload)
    os.replace(str(temporary), str(path))
    if s3_output_uri:
        bucket, prefix = parse_s3_uri(s3_output_uri)
        s3.put_object(Bucket=bucket, Key=prefix + "/" + filename, Body=payload,
                      ContentType="application/x-ndjson")
    return path


def validate_batch(path, expected_ids):
    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()]
    if ([row.get("content_id") for row in rows] != expected_ids
            or any(row.get("rule_version") != RULE_VERSION for row in rows)):
        raise RuntimeError("existing batch does not match current input/rules: {}".format(path))
    return rows


def cache_content(cache_dir, content_id, data):
    path = cache_dir / content_id[:2] / content_id
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        existing = path.read_bytes()
        if git_blob_sha1(existing) != content_id:
            raise RuntimeError("raw cache hash mismatch: {}".format(path))
        return existing
    if data is None:
        return None
    if git_blob_sha1(data) != content_id:
        return None
    temporary = path.with_suffix(".tmp")
    with temporary.open("wb") as handle:
        handle.write(data)
    os.replace(str(temporary), str(path))
    return data


def upload_raw_batch(s3, rows, output_dir, cache_dir, s3_output_uri, batch_number,
                     rebuild=False):
    archive_dir = output_dir / "raw_batches"
    archive_dir.mkdir(parents=True, exist_ok=True)
    archive = archive_dir / "batch-{:05d}.tar.gz".format(batch_number)
    if rebuild or not archive.exists():
        temporary = archive.with_suffix(".tmp")
        with tarfile.open(str(temporary), "w:gz") as handle:
            for row in rows:
                if row.get("fetch_status") not in ("fetched", "cached"):
                    continue
                content_id = row["content_id"]
                path = cache_dir / content_id[:2] / content_id
                if not path.exists():
                    raise RuntimeError("missing raw cache for {}".format(content_id))
                if git_blob_sha1(path.read_bytes()) != content_id:
                    raise RuntimeError("raw cache hash mismatch: {}".format(path))
                handle.add(str(path), arcname=content_id, recursive=False)
        os.replace(str(temporary), str(archive))
    if s3_output_uri:
        bucket, prefix = parse_s3_uri(s3_output_uri)
        raw_prefix = prefix.rsplit("/", 1)[0] + "/raw_batches"
        s3.upload_file(str(archive), bucket, raw_prefix + "/" + archive.name)
    return archive


def s3_client(region):
    import boto3
    import botocore.session
    from botocore.config import Config
    from botocore.credentials import RefreshableCredentials

    session = boto3.Session()
    if session.get_credentials() is None:
        # AWS CLI v2 login_session is not understood by older botocore releases.
        def refresh_from_aws_cli():
            result = subprocess.run(
                ["aws", "configure", "export-credentials", "--format", "process"],
                capture_output=True, text=True, check=True, timeout=30,
            )
            credentials = json.loads(result.stdout)
            return {
                "access_key": credentials["AccessKeyId"],
                "secret_key": credentials["SecretAccessKey"],
                "token": credentials.get("SessionToken"),
                "expiry_time": credentials["Expiration"],
            }

        botocore_session = botocore.session.get_session()
        refreshable = RefreshableCredentials.create_from_metadata(
            metadata=refresh_from_aws_cli(),
            refresh_using=refresh_from_aws_cli,
            method="aws-cli-login",
        )
        # AWS CLI login credentials live about 15 minutes; botocore's default
        # 15-minute advisory window would refresh on almost every S3 request.
        refreshable._advisory_refresh_timeout = 60
        refreshable._mandatory_refresh_timeout = 30
        botocore_session._credentials = refreshable
        session = boto3.Session(botocore_session=botocore_session)
    return session.client(
        "s3", region_name=region,
        config=Config(retries={"mode": "standard", "total_max_attempts": 4},
                      connect_timeout=10, read_timeout=20,
                      max_pool_connections=80),
    )


def public_s3_client(region):
    import boto3
    from botocore import UNSIGNED
    from botocore.config import Config

    return boto3.client(
        "s3", region_name=region,
        config=Config(signature_version=UNSIGNED,
                      retries={"mode": "standard", "total_max_attempts": 4},
                      connect_timeout=10, read_timeout=20,
                      max_pool_connections=80),
    )


def screen_one(content_id, args, s3, cache_dir, sha1_map):
    fetched_at = utc_now()
    data = cache_content(cache_dir, content_id, None)
    if data is not None:
        info = {"fetch_status": "cached", "bytes_read": len(data)}
    elif args.source == "s3" and content_id not in sha1_map:
        info = {"fetch_status": "unmapped"}
    elif args.source == "s3":
        data, info = fetch_content_s3(s3, content_id, sha1_map[content_id],
                                      args.max_bytes)
        if data is not None:
            cache_content(cache_dir, content_id, data)
    else:
        data, info = fetch_content(content_id, args.api_root, args.timeout,
                                   args.max_bytes, args.retries, args.token)
        if data is not None:
            cache_content(cache_dir, content_id, data)
    row = inspect_content(content_id, data) if data is not None else {
        "content_id": content_id, "rule_version": RULE_VERSION,
        "version_status": "uninspected", "quality_status": "unknown",
        "quality_flags": [],
    }
    if row.get("fetch_status") != "hash_mismatch":
        row.update(info)
    else:
        row["bytes_read"] = info.get("bytes_read")
    row["fetched_at_utc"] = fetched_at
    if args.source == "s3" and content_id in sha1_map:
        row["sha1"] = sha1_map[content_id]
    return row


def run(args):
    s3 = s3_client(args.region)
    ids = load_content_ids_cached(s3, args.input_uri, args.index_cache_dir)
    if args.expected_count and len(ids) != args.expected_count:
        raise RuntimeError("expected {} IDs, found {}".format(args.expected_count, len(ids)))
    sha1_map = load_sha1_map(s3, args.hash_map_uri, args.map_cache_dir,
                            args.map_workers) if args.source == "s3" else {}
    content_s3 = public_s3_client(args.region) if args.source == "s3" else s3
    if args.mapped_only:
        ids = [content_id for content_id in ids if content_id in sha1_map]
    selected = ids[args.offset:args.offset + args.limit] if args.limit else ids[args.offset:]
    if not selected:
        raise RuntimeError("no content IDs selected")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    cache_dir = args.output_dir / "raw_cache"
    started = time.monotonic()
    LOG.info("started_utc=%s total_ids=%d mapped_ids=%d selected=%d offset=%d",
             utc_now(), len(ids), len(sha1_map), len(selected), args.offset)
    counts = {}
    attempted = 0
    consecutive_rate_limits = 0
    stop_for_rate_limit = False
    for batch_start in range(0, len(selected), args.batch_size):
        number = args.offset + batch_start
        path = args.output_dir / "batch-{:05d}.jsonl".format(number)
        expected_ids = selected[batch_start:batch_start + args.batch_size]
        if path.exists() and not args.retry_batches:
            existing = validate_batch(path, expected_ids)
            retry_statuses = {"rate_limited", "network_error", "s3_error",
                              "decompression_error", "hash_mismatch"} if args.retry_errors else {"rate_limited"}
            if not any(row.get("fetch_status") in retry_statuses or row.get("http_status") == 429
                       for row in existing):
                if args.s3_output_uri:
                    bucket, prefix = parse_s3_uri(args.s3_output_uri)
                    s3.upload_file(str(path), bucket, prefix + "/" + path.name,
                                   ExtraArgs={"ContentType": "application/x-ndjson"})
                upload_raw_batch(s3, existing, args.output_dir, cache_dir,
                                 args.s3_output_uri, number)
                LOG.info("resumed batch=%d file=%s", number, path)
                continue
        rows = []
        if args.source == "s3" and args.workers > 1:
            batch_started = time.monotonic()
            last_report = batch_started
            with ThreadPoolExecutor(max_workers=args.workers) as executor:
                pending = {executor.submit(screen_one, content_id, args, content_s3, cache_dir, sha1_map): index
                           for index, content_id in enumerate(expected_ids)}
                rows = [None] * len(expected_ids)
                for completed_in_batch, future in enumerate(as_completed(pending), 1):
                    rows[pending[future]] = future.result()
                    current = time.monotonic()
                    if current - last_report >= 15:
                        LOG.info("batch=%d content_progress=%d/%d batch_elapsed_s=%.1f",
                                 number, completed_in_batch, len(expected_ids), current - batch_started)
                        last_report = current
        else:
            for content_id in expected_ids:
                row = screen_one(content_id, args, content_s3, cache_dir, sha1_map)
                rows.append(row)
                if row.get("http_status") == 429:
                    consecutive_rate_limits += 1
                else:
                    consecutive_rate_limits = 0
                if consecutive_rate_limits >= 3:
                    stop_for_rate_limit = True
                    break
                if args.delay and args.source == "api":
                    time.sleep(args.delay)
        for row in rows:
            status = row["fetch_status"]
            counts[status] = counts.get(status, 0) + 1
            attempted += 1
        if stop_for_rate_limit:
            for content_id in expected_ids[len(rows):]:
                rows.append({"content_id": content_id, "rule_version": RULE_VERSION,
                             "version_status": "uninspected", "quality_status": "unknown",
                             "quality_flags": [], "fetch_status": "rate_limited",
                             "fetched_at_utc": utc_now()})
                counts["rate_limited"] = counts.get("rate_limited", 0) + 1
        write_batch(s3, rows, args.output_dir, args.s3_output_uri, number)
        upload_raw_batch(s3, rows, args.output_dir, cache_dir,
                         args.s3_output_uri, number, rebuild=True)
        completed = batch_start + len(rows)
        elapsed = time.monotonic() - started
        rate = attempted / elapsed if elapsed else 0.0
        eta = (len(selected) - completed) / rate if rate else None
        finish = (dt.datetime.now(dt.timezone.utc) + dt.timedelta(seconds=eta)).isoformat() if eta else None
        LOG.info("batch=%d progress=%d/%d elapsed_s=%.1f ids_per_s=%.3f eta_s=%s estimated_finish_utc=%s statuses=%s",
                 number, completed, len(selected), elapsed, rate,
                 round(eta, 1) if eta else None, finish, counts)
        if stop_for_rate_limit:
            LOG.warning("three consecutive HTTP 429 responses; batch checkpoint saved, resume later")
            raise RuntimeError("SWH API rate limited; resume after the limit clears")
    LOG.info("finished_utc=%s statuses=%s", utc_now(), counts)


