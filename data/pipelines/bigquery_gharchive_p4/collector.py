def recursive_tree(http, repository, tree_sha):
    path = "repos/{}/git/trees/{}?recursive=1".format(
        urllib.parse.quote(repository, safe="/"), urllib.parse.quote(tree_sha, safe="")
    )
    payload, _ = http.get_json(github_api_url(path))
    if not payload.get("truncated"):
        return payload.get("tree", []), False

    entries = []
    pending = [(tree_sha, "")]
    while pending:
        current_sha, prefix = pending.pop()
        path = "repos/{}/git/trees/{}".format(
            urllib.parse.quote(repository, safe="/"), urllib.parse.quote(current_sha, safe="")
        )
        current, _ = http.get_json(github_api_url(path))
        for entry in current.get("tree", []):
            copied = dict(entry)
            copied["path"] = "{}{}".format(prefix, entry.get("path", ""))
            entries.append(copied)
            if entry.get("type") == "tree":
                pending.append((entry["sha"], copied["path"].rstrip("/") + "/"))
    return entries, True


def resolve_repo_record(http, record):
    record = dict(record)
    repository = normalize_repository(record.get("repository"))
    metadata = repo_metadata(http, repository)
    record.update(
        {
            "repository": repository,
            "repository_id": metadata.get("id", record.get("repository_id")),
            "html_url": metadata.get("html_url", "https://github.com/{}".format(repository)),
            "clone_url": metadata.get("clone_url", "https://github.com/{}.git".format(repository)),
            "default_branch": metadata.get("default_branch") or record.get("default_branch"),
            "is_fork": metadata.get("fork"),
            "is_archived": metadata.get("archived"),
            "is_empty": metadata.get("size", 0) == 0 and not metadata.get("default_branch"),
            "size_kb": metadata.get("size"),
            "license_spdx": (metadata.get("license") or {}).get("spdx_id") if isinstance(metadata.get("license"), dict) else None,
            "github_updated_at": metadata.get("updated_at"),
            "github_pushed_at": metadata.get("pushed_at"),
        }
    )
    if metadata.get("empty") or not metadata.get("default_branch"):
        record["status"] = "empty"
        record["latest_commit"] = None
        return record
    branch = record.get("default_branch")
    latest = latest_commit_for_branch(http, repository, branch)
    record["latest_commit"] = latest.get("sha")
    record["latest_commit_url"] = latest.get("html_url")
    record["status"] = "candidate"
    return record


class SnapshotCollector:
    def __init__(self, output_root, http, max_full_archive_bytes, max_full_archive_files, max_code_file_bytes):
        self.output_root = Path(output_root).resolve()
        self.http = http
        self.max_full_archive_bytes = int(max_full_archive_bytes)
        self.max_full_archive_files = int(max_full_archive_files)
        self.max_code_file_bytes = int(max_code_file_bytes)
        self.snapshots_root = self.output_root / "snapshots"
        self.manifest_root = self.output_root / "manifests"
        self.tree_root = self.manifest_root / "trees"
        self.snapshots_manifest = self.manifest_root / "snapshots.jsonl"
        self.files_manifest = self.manifest_root / "files.jsonl"
        self.errors_manifest = self.manifest_root / "errors.jsonl"
        self.filter_manifest = self.manifest_root / "file_filter_annotations.jsonl"
        self.repository_filter_manifest = self.manifest_root / "repository_filter_annotations.jsonl"
        self.max_in_memory_bytes = 8 * 1024 * 1024
        self.tree_index = {}
        self.commit_index = {}
        for existing in iter_jsonl(self.snapshots_manifest) or []:
            tree_hash = existing.get("tree_hash") or existing.get("tree_sha")
            reusable = existing.get("status") == "downloaded" and (
                existing.get("full_content") is True or existing.get("code_complete") is True
            )
            if tree_hash and reusable:
                self.tree_index.setdefault(tree_hash, existing)
            repository = normalize_repository(existing.get("repository"))
            commit_sha = existing.get("commit_sha")
            if repository and commit_sha and reusable:
                self.commit_index.setdefault((repository.lower(), commit_sha), existing)

    def snapshot_id(self, source_kind, repository, commit_sha):
        safe_repo = normalize_repository(repository).replace("/", "__")
        safe_source = re.sub(r"[^A-Za-z0-9_.-]+", "_", source_kind or "github")
        return "{}__{}__{}".format(safe_source, safe_repo, commit_sha)

    def snapshot_dir(self, source_kind, repository, commit_sha):
        return self.snapshots_root / re.sub(r"[^A-Za-z0-9_.-]+", "_", source_kind or "github") / normalize_repository(repository).replace("/", "__") / commit_sha

    def _write_tree_manifest(self, snapshot_id, tree_entries, truncated):
        path = self.tree_root / (snapshot_id + ".jsonl")
        temporary = path.with_name(path.name + ".partial")
        temporary.parent.mkdir(parents=True, exist_ok=True)
        with temporary.open("w", encoding="utf-8") as handle:
            for entry in sorted(tree_entries, key=lambda item: item.get("path", "")):
                record = {
                    "snapshot_id": snapshot_id,
                    "path": entry.get("path"),
                    "type": entry.get("type"),
                    "mode": entry.get("mode"),
                    "sha": entry.get("sha"),
                    "size_bytes": entry.get("size"),
                    "content_class": classify_path(entry.get("path", ""), entry.get("size") or 0),
                    "tree_api_truncated": bool(truncated),
                }
                record.update(path_metadata(entry.get("path")))
                record["is_symlink"] = str(entry.get("mode") or "").startswith("120")
                record["is_submodule"] = entry.get("type") == "commit"
                handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")
        temporary.replace(path)
        return path

    def _tree_records(self, tree_entries, snapshot_id):
        records = []
        for entry in tree_entries:
            path = entry.get("path") or ""
            record = {
                "snapshot_id": snapshot_id,
                "path": path,
                "type": entry.get("type"),
                "mode": entry.get("mode"),
                "git_blob_sha": entry.get("sha") if entry.get("type") == "blob" else None,
                "size_bytes": entry.get("size"),
                "content_class": classify_path(path, entry.get("size") or 0),
                "content_status": "not_fetched" if entry.get("type") == "blob" else "pointer_or_tree",
                "content_location": None,
            }
            record.update(path_metadata(path))
            record["is_symlink"] = str(entry.get("mode") or "").startswith("120")
            record["is_submodule"] = entry.get("type") == "commit"
            records.append(record)
        return records

    def _raw_url(self, repository, commit_sha, path):
        return "https://raw.githubusercontent.com/{}/{}/{}".format(
            normalize_repository(repository),
            urllib.parse.quote(commit_sha, safe=""),
            "/".join(urllib.parse.quote(part, safe="") for part in path.split("/")),
        )

    def _fetch_blob(self, repository, commit_sha, path, expected_sha=None):
        data = self.http.get_bytes(self._raw_url(repository, commit_sha, path), headers={"Accept": "application/octet-stream"})
        actual_sha = git_blob_sha1(data)
        return data, actual_sha, (expected_sha is None or actual_sha == expected_sha)

    def _fetch_blob_file(self, repository, commit_sha, path, destination, expected_sha=None):
        size, sha256 = self.http.download(
            self._raw_url(repository, commit_sha, path),
            destination,
            headers={"Accept": "application/octet-stream"},
        )
        actual_sha = git_blob_sha1_file(destination, size)
        return (
            actual_sha,
            (expected_sha is None or actual_sha == expected_sha),
            size,
            sha256,
            is_git_lfs_pointer_file(destination),
        )

    def _resolve_include_path(self, including_path, include_name, all_paths):
        include_name = include_name.replace("\\", "/").lstrip("./")
        candidates = []
        parent = Path(including_path).parent
        candidates.append(str(parent / include_name).replace("\\", "/"))
        candidates.append(include_name)
        basename = Path(include_name).name
        candidates.extend(path for path in all_paths if Path(path).name == basename)
        for candidate in candidates:
            candidate = str(Path(candidate)).replace("\\", "/")
            if candidate in all_paths:
                return candidate
        return None

    def _inspect_p4_gate(self, repository, commit_sha, tree_records):
        """Fetch only .p4 blobs and decide project admission before payload download."""
        readable_paths = []
        p4_16_paths = []
        conflicted_paths = []
        for record in tree_records:
            if record.get("type") != "blob" or Path(record.get("path", "")).suffix.lower() != ".p4":
                continue
            if (record.get("size_bytes") or 0) > self.max_code_file_bytes:
                record.update(
                    {
                        "p4_gate_status": "skipped_too_large",
                        "p4_version_status": "unknown",
                    }
                )
                continue
            try:
                data, actual_sha, sha_matches = self._fetch_blob(
                    repository,
                    commit_sha,
                    record["path"],
                    record.get("git_blob_sha"),
                )
            except Exception as exc:
                record.update(
                    {
                        "p4_gate_status": "fetch_failed",
                        "p4_gate_error": str(exc),
                        "p4_version_status": "unknown",
                    }
                )
                continue
            if not sha_matches:
                record.update(
                    {
                        "p4_gate_status": "sha_mismatch",
                        "p4_gate_git_blob_sha_actual": actual_sha,
                        "p4_version_status": "unknown",
                    }
                )
                continue
            if is_git_lfs_pointer(data):
                record.update(
                    {
                        "p4_gate_status": "lfs_pointer",
                        "p4_version_status": "unknown",
                    }
                )
                continue
            classification = classify_p4_bytes(data)
            record.update(classification)
            record.update(
                {
                    "p4_gate_status": "fetched",
                    "p4_gate_bytes": len(data),
                    "p4_gate_sha256": sha256_bytes(data),
                }
            )
            readable_paths.append(record["path"])
            if classification["p4_version_status"] == "p4_16":
                p4_16_paths.append(record["path"])
            elif classification["p4_version_status"] == "p4_16_conflicted":
                conflicted_paths.append(record["path"])
        return {
            "readable_p4_paths": sorted(readable_paths),
            "p4_16_paths": sorted(p4_16_paths),
            "p4_16_conflicted_paths": sorted(conflicted_paths),
        }

    def _fetch_layered_code(self, repository, commit_sha, tree_records, destination):
        code_root = destination / "code_payload"
        code_root.mkdir(parents=True, exist_ok=True)
        by_path = {record["path"]: record for record in tree_records if record.get("type") == "blob"}
        all_paths = set(by_path)
        selected = {
            path
            for path, record in by_path.items()
            if record["content_class"] in {"code", "context"}
        }
        for path, record in by_path.items():
            if record.get("size_bytes") and record["size_bytes"] > self.max_code_file_bytes:
                record["large_code"] = True
        fetched = {}
        missing = []
        large_code = []
        include_queue = []
        include_edges = set()
        for path in sorted(selected):
            target = code_root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            declared_size = by_path[path].get("size_bytes") or 0
            try:
                if declared_size > self.max_in_memory_bytes:
                    actual_sha, sha_matches, fetched_size, content_sha256, lfs_pointer = self._fetch_blob_file(
                        repository, commit_sha, path, target, by_path[path].get("git_blob_sha")
                    )
                    data = None
                else:
                    data, actual_sha, sha_matches = self._fetch_blob(repository, commit_sha, path, by_path[path].get("git_blob_sha"))
                    target.write_bytes(data)
                    fetched_size = len(data)
                    content_sha256 = sha256_bytes(data)
                    lfs_pointer = is_git_lfs_pointer(data)
            except Exception as exc:
                by_path[path]["content_status"] = "fetch_failed"
                by_path[path]["error"] = str(exc)
                missing.append(path)
                continue
            if data is not None:
                fetched[path] = data
            by_path[path].update(
                {
                    "content_status": "lfs_pointer" if lfs_pointer else ("fetched" if sha_matches else "sha_mismatch"),
                    "content_location": str(target.relative_to(self.output_root)),
                    "sha256": content_sha256,
                    "git_blob_sha_actual": actual_sha,
                    "fetched_size_bytes": fetched_size,
                }
            )
            if not sha_matches:
                missing.append(path)
            if lfs_pointer:
                by_path[path]["lfs_pointer"] = True
                missing.append(path)
            if by_path[path].get("large_code"):
                large_code.append(path)
            if Path(path).suffix.lower() in {".p4", ".p4i"} and data is not None:
                include_queue.extend((path, include_name) for include_name in parse_p4_includes(data))
            elif Path(path).suffix.lower() in {".p4", ".p4i"}:
                by_path[path]["include_scan"] = "skipped_large_in_memory_limit"

        unresolved_includes = []
        queue_index = 0
        while queue_index < len(include_queue):
            including_path, include_name = include_queue[queue_index]
            queue_index += 1
            edge = (including_path, include_name)
            if edge in include_edges:
                continue
            include_edges.add(edge)
            resolved = self._resolve_include_path(including_path, include_name, all_paths)
            if not resolved:
                if is_standard_external_include(include_name):
                    continue
                unresolved_includes.append({"including_path": including_path, "include": include_name})
                continue
            if resolved in fetched:
                continue
            record = by_path[resolved]
            target = code_root / resolved
            target.parent.mkdir(parents=True, exist_ok=True)
            declared_size = record.get("size_bytes") or 0
            try:
                if declared_size > self.max_in_memory_bytes:
                    actual_sha, sha_matches, fetched_size, content_sha256, lfs_pointer = self._fetch_blob_file(
                        repository, commit_sha, resolved, target, record.get("git_blob_sha")
                    )
                    data = None
                else:
                    data, actual_sha, sha_matches = self._fetch_blob(repository, commit_sha, resolved, record.get("git_blob_sha"))
                    target.write_bytes(data)
                    fetched_size = len(data)
                    content_sha256 = sha256_bytes(data)
                    lfs_pointer = is_git_lfs_pointer(data)
            except Exception as exc:
                record["content_status"] = "fetch_failed"
                record["error"] = str(exc)
                missing.append(resolved)
                continue
            if data is not None:
                fetched[resolved] = data
            record.update(
                {
                    "content_class": "code",
                    "content_status": "lfs_pointer" if lfs_pointer else ("fetched" if sha_matches else "sha_mismatch"),
                    "content_location": str(target.relative_to(self.output_root)),
                    "sha256": content_sha256,
                    "git_blob_sha_actual": actual_sha,
                    "fetched_size_bytes": fetched_size,
                    "include_dependency": True,
                }
            )
            if not sha_matches:
                missing.append(resolved)
            if lfs_pointer:
                record["lfs_pointer"] = True
                missing.append(resolved)
            if Path(resolved).suffix.lower() in {".p4", ".p4i"} and data is not None:
                include_queue.extend((resolved, nested) for nested in parse_p4_includes(data))

        for record in tree_records:
            if record.get("type") != "blob":
                continue
            if record["path"] not in fetched and record["path"] not in missing:
                if record["content_class"] == "optional":
                    record["content_status"] = "omitted_optional"
                else:
                    record["content_status"] = "not_fetched"
        return {
            "code_payload_path": str(code_root.relative_to(self.output_root)),
            "fetched": fetched,
            "missing_code_paths": sorted(set(missing)),
            "large_code_paths": sorted(set(large_code)),
            "unresolved_includes": unresolved_includes,
        }

    def _inspect_archive(self, archive_path, tree_records, snapshot_id):
        expected = {record["path"]: record for record in tree_records if record.get("type") == "blob"}
        seen = set()
        annotations = []
        errors = []
        with tarfile.open(str(archive_path), "r:gz") as archive:
            members = archive.getmembers()
            for member in members:
                safe_name = safe_archive_member_name(member.name)
                if not safe_name or "/" not in safe_name:
                    continue
                relative = safe_name.split("/", 1)[1]
                if relative not in expected:
                    continue
                seen.add(relative)
                record = expected[relative]
                record["content_location"] = "archive:{}".format(safe_name)
                if member.issym() or member.islnk():
                    record["content_status"] = "symlink"
                    continue
                if not member.isfile():
                    record["content_status"] = "not_regular_file"
                    continue
                extracted = archive.extractfile(member)
                data = None
                if extracted:
                    actual_sha, content_sha256, collected = hash_stream(
                        extracted,
                        member.size,
                        collect=record.get("content_class") in {"code", "context"} and member.size <= MAX_ANNOTATION_BYTES,
                    )
                    data = collected
                else:
                    actual_sha = git_blob_sha1(b"")
                    content_sha256 = sha256_bytes(b"")
                lfs_pointer = data is not None and is_git_lfs_pointer(data)
                record.update(
                    {
                        "content_status": "lfs_pointer" if lfs_pointer else ("fetched" if actual_sha == record.get("git_blob_sha") else "sha_mismatch"),
                        "sha256": content_sha256,
                        "git_blob_sha_actual": actual_sha,
                    }
                )
                if lfs_pointer:
                    record["lfs_pointer"] = True
                if actual_sha != record.get("git_blob_sha"):
                    errors.append({"path": relative, "reason": "git_blob_sha_mismatch"})
                if record.get("content_class") in {"code", "context"} and data is not None:
                    annotation = basic_file_annotations(data, relative)
                    annotation["snapshot_id"] = snapshot_id
                    annotations.append(annotation)
                elif record.get("content_class") in {"code", "context"}:
                    annotations.append(
                        {
                            "snapshot_id": snapshot_id,
                            "path": relative,
                            "size_bytes": member.size,
                            "annotation_skipped": "larger_than_{}MB".format(MAX_ANNOTATION_BYTES // (1024 * 1024)),
                            "reasons": ["large_file_annotation_skipped"],
                        }
                    )
            for path, record in expected.items():
                if path not in seen:
                    record["content_status"] = "missing_from_archive"
                    errors.append({"path": path, "reason": "missing_from_archive"})
        return annotations, errors

