def command_collect_snapshots(args):
    output_root = Path(args.output_root).resolve()
    http = HttpClient(token=args.token, proxy=args.proxy, timeout=args.timeout, retries=args.retries)
    collector = SnapshotCollector(
        output_root,
        http,
        max_full_archive_bytes=args.max_full_archive_bytes,
        max_full_archive_files=args.max_full_archive_files,
        max_code_file_bytes=args.max_code_file_bytes,
    )
    records = list(iter_jsonl(args.repositories) or [])
    if args.source_kind:
        records = [record for record in records if source_matches(record, args.source_kind)]
    total_before_selection = len(records)
    records = records[max(0, int(args.offset)) :]
    if args.limit:
        records = records[: max(0, int(args.limit))]
    summary = {
        "total": len(records),
        "total_before_selection": total_before_selection,
        "offset": int(args.offset),
        "limit": int(args.limit),
        "downloaded": 0,
        "failed": 0,
        "eligible": 0,
        "rejected_not_p4_16": 0,
        "code_incomplete": 0,
    }
    for record in records:
        if record.get("status") == "empty":
            continue
        if args.skip_estimated_oversize and record.get("size_kb") is not None and int(record.get("size_kb") or 0) * 1024 > args.max_full_archive_bytes * 5:
            append_jsonl(
                collector.repository_filter_manifest,
                {
                    "repository": record.get("repository"),
                    "repository_id": record.get("repository_id"),
                    "status": "quarantine",
                    "reason": "estimated_repository_size_over_5x_archive_limit",
                    "size_kb": record.get("size_kb"),
                    "rule_version": SCRIPT_VERSION,
                    "time": utc_now(),
                },
            )
            continue
        try:
            if not record.get("latest_commit"):
                record = resolve_repo_record(http, record)
            if record.get("status") == "empty" or not record.get("latest_commit"):
                append_jsonl(
                    collector.errors_manifest,
                    {
                        "repository": record.get("repository"),
                        "reason": "empty_or_no_default_commit",
                        "time": utc_now(),
                    },
                )
                continue
            source_kind = snapshot_source_kind(record, args.source_kind)
            result = collector.collect_one(record, source_kind=source_kind)
        except Exception as exc:
            result = {"status": "failed", "error": str(exc)}
        if result.get("status") == "failed":
            summary["failed"] += 1
        elif result.get("status") == "rejected":
            summary["rejected_not_p4_16"] += 1
        else:
            summary["downloaded"] += 1
            if result.get("project_status") in {"eligible", "eligible_with_warnings"}:
                summary["eligible"] += 1
            if result.get("project_status") == "code_incomplete":
                summary["code_incomplete"] += 1
    write_json(output_root / "manifests" / "collection_summary.json", {**summary, "completed_at": utc_now()})
    print(json.dumps(summary, ensure_ascii=False, indent=2))


def select_history_records(push_events, mode="window", max_per_repository=20, max_total=None, repositories=None):
    """Select deterministic historical commit records from PushEvent JSONL."""
    if mode == "none":
        return []
    allowed = None
    if repositories is not None:
        allowed = {
            normalize_repository(item.get("repository") or item.get("repo_name")).lower()
            for item in repositories
            if normalize_repository(item.get("repository") or item.get("repo_name"))
        }
    grouped = {}
    for event in push_events:
        repository = normalize_repository(event.get("repository"))
        head_sha = str(event.get("head_sha") or "")
        ref = str(event.get("ref") or "")
        if not repository or not head_sha or not ref.startswith("refs/heads/"):
            continue
        if allowed is not None and repository.lower() not in allowed:
            continue
        key = (repository.lower(), head_sha)
        grouped.setdefault(key, dict(event))
    records = []
    by_repository = {}
    for event in grouped.values():
        repository = normalize_repository(event.get("repository"))
        by_repository.setdefault(repository.lower(), []).append(event)
    for repository_key in sorted(by_repository):
        events = sorted(
            by_repository[repository_key],
            key=lambda item: (str(item.get("created_at") or ""), str(item.get("head_sha") or "")),
            reverse=True,
        )
        if mode == "window":
            events = events[: max(1, int(max_per_repository))]
        for event in events:
            records.append(
                {
                    "source_kind": "gharchive_history",
                    "discovery_basis": "gharchive_push_event",
                    "repository": normalize_repository(event.get("repository")),
                    "repository_id": event.get("repository_id"),
                    "commit_sha": event.get("head_sha"),
                    "ref": event.get("ref"),
                    "before_sha": event.get("before_sha"),
                    "observed_event_id": event.get("event_id"),
                    "created_at": event.get("created_at"),
                    "source_url": event.get("source_url"),
                    "contains_p4": None,
                    "p4_verification_status": "unverified",
                }
            )
    if max_total is not None:
        records = records[: max(0, int(max_total))]
    return records


def command_collect_history(args):
    output_root = Path(args.output_root).resolve()
    http = HttpClient(token=args.token, proxy=args.proxy, timeout=args.timeout, retries=args.retries)
    collector = SnapshotCollector(
        output_root,
        http,
        max_full_archive_bytes=args.max_full_archive_bytes,
        max_full_archive_files=args.max_full_archive_files,
        max_code_file_bytes=args.max_code_file_bytes,
    )
    events = list(iter_jsonl(args.push_events) or [])
    repositories = list(iter_jsonl(args.repositories) or [])
    records = select_history_records(
        events,
        mode=args.mode,
        max_per_repository=args.max_per_repository,
        max_total=args.max_total,
        repositories=repositories,
    )
    summary = {
        "selected": len(records),
        "downloaded": 0,
        "failed": 0,
        "eligible": 0,
        "rejected_not_p4_16": 0,
        "code_incomplete": 0,
    }
    for record in records:
        try:
            result = collector.collect_one(record, source_kind="history")
        except Exception as exc:
            result = {"status": "failed", "error": str(exc)}
        if result.get("status") == "failed":
            summary["failed"] += 1
        elif result.get("status") == "rejected":
            summary["rejected_not_p4_16"] += 1
        else:
            summary["downloaded"] += 1
            if result.get("project_status") in {"eligible", "eligible_with_warnings"}:
                summary["eligible"] += 1
            if result.get("project_status") == "code_incomplete":
                summary["code_incomplete"] += 1
    write_json(output_root / "manifests" / "history_collection_summary.json", {**summary, "mode": args.mode, "completed_at": utc_now()})
    print(json.dumps(summary, ensure_ascii=False, indent=2))


