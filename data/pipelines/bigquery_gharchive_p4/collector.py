def main(argv=None):
    load_dotenv_candidates()
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.command == "discover-bigquery" and args.execute and not args.billing_project:
        parser.error("discover-bigquery --execute requires --billing-project")
    try:
        return args.func(args) or 0
    except KeyboardInterrupt:
        return 130
    except Exception as exc:
        print("ERROR: {}".format(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
