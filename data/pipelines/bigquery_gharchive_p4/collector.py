def safe_archive_member_name(name):
    name = str(name).replace("\\", "/")
    while name.startswith("./"):
        name = name[2:]
    path = Path(name)
    if path.is_absolute() or ".." in path.parts:
        raise ValueError("unsafe archive path: {}".format(name))
    return name


def decode_bq_value(value):
    if isinstance(value, list):
        return [decode_bq_value(item.get("v") if isinstance(item, dict) and "v" in item else item) for item in value]
    if isinstance(value, dict) and "v" in value:
        return decode_bq_value(value["v"])
    return value


class HttpClient:
    """Small stdlib HTTP client with retry and rate-limit handling."""

    def __init__(self, token=None, proxy=None, timeout=60.0, retries=3, user_agent=None):
        self.token = token or os.environ.get("GITHUB_TOKEN")
        self.proxy = proxy
        self.timeout = float(timeout)
        self.retries = max(1, int(retries))
        self.user_agent = user_agent or "p4-raw-collector/{}".format(SCRIPT_VERSION)
        handlers = []
        if proxy:
            handlers.append(urllib.request.ProxyHandler({"http": proxy, "https": proxy}))
        else:
            handlers.append(urllib.request.ProxyHandler({}))
        self.opener = urllib.request.build_opener(*handlers)

    def _headers(self, extra=None):
        headers = {"User-Agent": self.user_agent, "Accept": "application/json"}
        if self.token:
            headers["Authorization"] = "Bearer {}".format(self.token)
        if extra:
            headers.update(extra)
        return headers

    def request(self, url, method="GET", data=None, headers=None):
        if data is not None and not isinstance(data, bytes):
            data = json.dumps(data).encode("utf-8")
        request = urllib.request.Request(url, data=data, headers=self._headers(headers), method=method)
        last_error = None
        for attempt in range(1, self.retries + 1):
            try:
                return self.opener.open(request, timeout=self.timeout)
            except urllib.error.HTTPError as exc:
                body = b""
                try:
                    body = exc.read(4096)
                except Exception:
                    pass
                last_error = "HTTP {} {}: {}".format(exc.code, url, body.decode("utf-8", errors="replace")[-1000:])
                retryable = exc.code in {408, 425, 429, 500, 502, 503, 504}
                if exc.code == 403 and (exc.headers.get("Retry-After") or "rate limit" in last_error.lower()):
                    retryable = True
                if not retryable or attempt >= self.retries:
                    raise RuntimeError(last_error)
                retry_after = exc.headers.get("Retry-After")
                try:
                    delay = min(60.0, max(1.0, float(retry_after))) if retry_after else min(30.0, 2.0 ** attempt)
                except ValueError:
                    delay = min(30.0, 2.0 ** attempt)
                time.sleep(delay)
            except (urllib.error.URLError, TimeoutError, OSError) as exc:
                last_error = "{}: {}".format(type(exc).__name__, exc)
                if attempt >= self.retries:
                    raise RuntimeError("request failed for {}: {}".format(url, last_error))
                time.sleep(min(30.0, 2.0 ** attempt))
        raise RuntimeError("request failed for {}: {}".format(url, last_error))

    def get_bytes(self, url, headers=None):
        with self.request(url, headers=headers) as response:
            return response.read()

    def get_json(self, url):
        with self.request(url) as response:
            body = response.read()
            return json.loads(body.decode("utf-8")), response.headers

    def post_json(self, url, payload):
        with self.request(url, method="POST", data=payload, headers={"Content-Type": "application/json"}) as response:
            body = response.read()
            return json.loads(body.decode("utf-8")), response.headers

    def download(self, url, destination, headers=None):
        destination = Path(destination)
        destination.parent.mkdir(parents=True, exist_ok=True)
        partial = destination.with_name(destination.name + ".partial")
        with self.request(url, headers=headers) as response, partial.open("wb") as handle:
            while True:
                chunk = response.read(1024 * 1024)
                if not chunk:
                    break
                handle.write(chunk)
        partial.replace(destination)
        return destination.stat().st_size, sha256_file(destination)


def sha256_file(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def parse_hour(value):
    return dt.datetime.strptime(value, "%Y-%m-%d-%H").replace(tzinfo=dt.timezone.utc)


def hour_range(start, end):
    current = parse_hour(start)
    stop = parse_hour(end)
    if stop < current:
        raise ValueError("end hour precedes start hour")
    while current <= stop:
        yield current
        current += dt.timedelta(hours=1)


class BigQueryClient:
    def __init__(self, billing_project, token=None, token_file=None, proxy=None, timeout=60.0, retries=3):
        self.billing_project = billing_project
        self.token = token or os.environ.get("BIGQUERY_ACCESS_TOKEN") or os.environ.get("GOOGLE_OAUTH_ACCESS_TOKEN")
        token_path = Path(token_file) if token_file else None
        if not self.token and token_path and token_path.is_file():
            try:
                from google.auth.transport.requests import Request
                from google.oauth2.credentials import Credentials
            except ImportError as exc:
                raise RuntimeError(
                    "loading an OAuth token file requires google-auth; install "
                    "google-cloud-bigquery and google-auth-oauthlib"
                ) from exc
            credentials = Credentials.from_authorized_user_file(
                str(token_path), ["https://www.googleapis.com/auth/bigquery"]
            )
            if credentials.expired and credentials.refresh_token:
                credentials.refresh(Request())
                temporary = token_path.with_name(token_path.name + ".tmp")
                temporary.write_text(credentials.to_json(), encoding="utf-8")
                temporary.chmod(0o600)
                os.replace(str(temporary), str(token_path))
            if credentials.valid:
                self.token = credentials.token
        if not self.token:
            try:
                result = subprocess.run(
                    ["gcloud", "auth", "application-default", "print-access-token"],
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    check=False,
                    timeout=30,
                )
            except (OSError, subprocess.TimeoutExpired):
                result = None
            if result and result.returncode == 0:
                self.token = result.stdout.strip()
        if not self.token:
            raise RuntimeError("set BIGQUERY_ACCESS_TOKEN or configure gcloud application-default credentials")
        self.http = HttpClient(token=self.token, proxy=proxy, timeout=timeout, retries=retries)

    def query(self, query, dry_run=False, max_bytes_billed=None):
        payload = {"query": query, "useLegacySql": False, "dryRun": bool(dry_run)}
        if max_bytes_billed is not None:
            payload["maximumBytesBilled"] = str(max_bytes_billed)
        url = "https://bigquery.googleapis.com/bigquery/v2/projects/{}/queries".format(
            urllib.parse.quote(self.billing_project, safe="")
        )
        result, _ = self.http.post_json(url, payload)
        if result.get("error") or result.get("errors"):
            raise RuntimeError("BigQuery query failed: {}".format(result.get("error") or result.get("errors")))
        if dry_run:
            return result
        job_reference = result.get("jobReference", {})
        job_id = job_reference.get("jobId")
        location = result.get("jobReference", {}).get("location")
        rows = list(result.get("rows", []))
        schema = result.get("schema", {})
        page_token = result.get("pageToken")
        while job_id and result.get("jobComplete") is not True:
            time.sleep(1.0)
            params = {"maxResults": "10000"}
            if page_token:
                params["pageToken"] = page_token
            if location:
                params["location"] = location
            get_url = "https://bigquery.googleapis.com/bigquery/v2/projects/{}/queries/{}?{}".format(
                urllib.parse.quote(self.billing_project, safe=""),
                urllib.parse.quote(job_id, safe=""),
                urllib.parse.urlencode(params),
            )
            result, _ = self.http.get_json(get_url)
            if result.get("error") or result.get("errors"):
                raise RuntimeError("BigQuery query failed: {}".format(result.get("error") or result.get("errors")))
            rows.extend(result.get("rows", []))
            schema = result.get("schema", schema)
            page_token = result.get("pageToken")
        while page_token:
            params = {"maxResults": "10000", "pageToken": page_token}
            if location:
                params["location"] = location
            get_url = "https://bigquery.googleapis.com/bigquery/v2/projects/{}/queries/{}?{}".format(
                urllib.parse.quote(self.billing_project, safe=""),
                urllib.parse.quote(job_id, safe=""),
                urllib.parse.urlencode(params),
            )
            result, _ = self.http.get_json(get_url)
            if result.get("error") or result.get("errors"):
                raise RuntimeError("BigQuery query failed: {}".format(result.get("error") or result.get("errors")))
            rows.extend(result.get("rows", []))
            page_token = result.get("pageToken")
        fields = [field["name"] for field in schema.get("fields", [])]
        decoded = []
        for row in rows:
            values = [decode_bq_value(cell.get("v")) for cell in row.get("f", [])]
            decoded.append(dict(zip(fields, values)))
        return {"job_id": job_id, "schema": schema, "rows": decoded, "total_rows": len(decoded)}


def make_schema_query(dataset="bigquery-public-data.github_repos", table="files"):
    return (
        "SELECT column_name, data_type, ordinal_position, is_nullable "
        "FROM `{dataset}.INFORMATION_SCHEMA.COLUMNS` "
        "WHERE table_name = '{table}' ORDER BY ordinal_position"
    ).format(dataset=dataset, table=table)


def select_schema_field(rows, choices):
    names = {str(row.get("column_name", "")).lower(): row.get("column_name") for row in rows}
    for choice in choices:
        if choice.lower() in names:
            return names[choice.lower()]
    return None


def sql_string(value):
    return "'{}'".format(str(value).replace("\\", "\\\\").replace("'", "''"))


def make_candidate_query(
    repo_field,
    path_field,
    dataset="bigquery-public-data.github_repos",
    table="files",
    repositories=None,
):
    table_ref = "`{}.{}`".format(dataset, table)
    repository_filter = ""
    if repositories:
        normalized = sorted(
            {
                normalize_repository(repository).lower()
                for repository in repositories
                if normalize_repository(repository)
            }
        )
        if len(normalized) > 10000:
            raise ValueError(
                "repository-restricted BigQuery mode accepts at most 10,000 names; "
                "use the single global .p4 query for larger candidate sets"
            )
        values = ", ".join(sql_string(repository) for repository in normalized)
        repository_filter = "LOWER(`{repo}`) IN UNNEST([{values}]) AND ".format(
            repo=repo_field,
            values=values,
        )
    return (
        "SELECT `{repo}` AS repo_name, "
        "COUNT(*) AS p4_file_count, "
        "ARRAY_AGG(`{path}` IGNORE NULLS LIMIT 100) AS example_paths "
        "FROM {table} "
        "WHERE {repository_filter}REGEXP_CONTAINS(LOWER(`{path}`), r'(^|/)[^/]+\\.p4$') "
        "GROUP BY `{repo}`"
    ).format(
        repo=repo_field,
        path=path_field,
        table=table_ref,
        repository_filter=repository_filter,
    )


