def classify_path(path, size=0):
    """Classify a tree path without reading its content.

    ``code`` means the blob belongs in the default layered code payload;
    ``context`` means a small, useful project/document file; ``optional`` is a
    large binary, cache, generated-output or dataset-like object.  The tree
    manifest always records every path regardless of this classification.
    """
    path = str(path).replace("\\", "/")
    parts = [part for part in path.split("/") if part]
    lower_parts = {part.lower() for part in parts}
    name = parts[-1] if parts else ""
    lower_name = name.lower()
    lower_stem = Path(name).stem.lower()
    suffix = Path(name).suffix.lower()

    if suffix in {".p4", ".p4i"}:
        return "code"
    if lower_parts.intersection(OPTIONAL_PARTS):
        return "optional"
    if name in SPECIAL_CODE_NAMES:
        return "code"
    if suffix in OPTIONAL_EXTENSIONS:
        return "optional"
    if suffix in CODE_EXTENSIONS:
        if suffix == ".json" and (lower_parts.intersection(SUSPICIOUS_DATA_PARTS) or lower_stem in SUSPICIOUS_DATA_PARTS):
            return "optional"
        return "code"
    if suffix in DOCUMENT_EXTENSIONS:
        if lower_parts.intersection(SUSPICIOUS_DATA_PARTS):
            return "optional"
        return "context" if size <= 2 * 1024 * 1024 else "optional"
    if lower_name in {"license", "copying", "notice", "authors", "contributors"}:
        return "context"
    if size and size <= 256 * 1024:
        return "context"
    return "optional"


def path_metadata(path):
    """Return stable, lightweight metadata shared by tree/file manifests."""
    path = str(path or "")
    name = Path(path).name
    suffix = Path(name).suffix.lower()
    mode_hint = None
    if name in SPECIAL_CODE_NAMES:
        mode_hint = "build_or_project_metadata"
    return {
        "extension": suffix,
        "language_hint": LANGUAGE_HINTS.get(suffix) or mode_hint,
        "is_symlink": False,
        "is_submodule": False,
    }


def basic_file_annotations(data, path):
    """Return StarCoder2-inspired, non-destructive file annotations."""
    suffix = Path(path).suffix.lower()
    result = {
        "path": str(path),
        "size_bytes": len(data),
        "line_count": None,
        "average_line_length": None,
        "maximum_line_length": None,
        "is_binary": b"\x00" in data,
        "reasons": [],
    }
    if result["is_binary"]:
        result["reasons"].append("binary_or_nul")
        return result
    text = data.decode("utf-8", errors="replace")
    lines = text.splitlines()
    result["line_count"] = len(lines)
    result["average_line_length"] = (
        float(sum(len(line) for line in lines)) / len(lines) if lines else 0.0
    )
    result["maximum_line_length"] = max((len(line) for line in lines), default=0)
    if not text.strip():
        result["reasons"].append("empty_or_whitespace")
    if len(lines) > 100000:
        result["reasons"].append("more_than_100k_lines")
    first_lines = "\n".join(lines[:5]).lower()
    if any(marker in first_lines for marker in AUTOGENERATED_MARKERS):
        result["reasons"].append("autogenerated_marker")
    if suffix not in {".html", ".htm", ".json", ".md", ".markdown", ".xml", ".rst", ".tex", ".txt"}:
        if result["average_line_length"] > 100:
            result["reasons"].append("average_line_length_over_100")
        if result["maximum_line_length"] > 1000:
            result["reasons"].append("maximum_line_length_over_1000")
    else:
        if result["maximum_line_length"] > 100000:
            result["reasons"].append("maximum_line_length_over_100k")
    if suffix not in {".p4", ".p4i"}:
        encoded_patterns = (
            rb"[A-Za-z0-9+/\n=]{64,}",
            rb"(?:\b(?:0x|\\x)?[0-9a-fA-F]{2}(?:,|\b\s*)){8,}",
            rb"(?:\\u[0-9a-fA-F]{4}){8,}",
        )
        encoded = 0
        for pattern in encoded_patterns:
            for match in re.finditer(pattern, data):
                if len(match.group(0)) > 1024:
                    encoded += len(match.group(0))
        if encoded and encoded >= len(data) * 0.5:
            result["reasons"].append("encoded_data_suspect")
    return result


def parse_p4_includes(data):
    text = data.decode("utf-8", errors="replace")
    return re.findall(r"^\s*#\s*include\s*[<\"]([^>\"]+)[>\"]", text, re.MULTILINE)


def classify_p4_bytes(data):
    source = data.decode("utf-8", errors="replace")
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.DOTALL)
    source = re.sub(r"//.*", "", source)
    positives = [pattern.pattern for pattern in P4_16_POSITIVE_PATTERNS if pattern.search(source)]
    negatives = [pattern.pattern for pattern in P4_14_NEGATIVE_PATTERNS if pattern.search(source)]
    if positives and not negatives:
        status = "p4_16"
    elif negatives and not positives:
        status = "p4_14"
    elif positives and negatives:
        status = "p4_16_conflicted"
    else:
        status = "unknown"
    return {
        "p4_version_status": status,
        "positive_signal_count": len(positives),
        "negative_signal_count": len(negatives),
        "positive_signals": positives[:5],
        "negative_signals": negatives[:5],
    }


