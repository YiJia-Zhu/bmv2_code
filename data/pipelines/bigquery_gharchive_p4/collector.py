"""Collect provenance-preserving P4 GitHub project snapshots.

The collector is intentionally phase-oriented.  GHArchive is the default
repository-discovery source, while the optional BigQuery path remains
available as a separate candidate source.  Discovery metadata, GHArchive
events, repository trees, code payloads and optional large files are kept in
separate, auditable outputs.  A repository that contains a ``.p4`` file is
never reduced to a ``.p4``-only download: the complete tree is recorded and
all code/context files are fetched in layered mode.  GHArchive candidates do
not claim P4 content until the GitHub snapshot tree has been inspected.

Network operations are opt-in through explicit subcommands.  The default
arguments are suitable for the proposed raw collection, but this module does
not run a query or download anything merely by being imported.
"""

