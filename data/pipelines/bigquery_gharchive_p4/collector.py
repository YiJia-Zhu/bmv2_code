def paginate_github(http, url):
    while url:
        page, headers = http.get_json(url)
        yield page
        link = headers.get("Link", "")
        next_url = None
        for part in link.split(","):
            match = re.search(r"<([^>]+)>;\s*rel=\"next\"", part)
            if match:
                next_url = match.group(1)
                break
        url = next_url


