def is_git_lfs_pointer(data):
    if not data:
        return False
    prefix = data[:512].decode("utf-8", errors="replace")
    return prefix.startswith("version https://git-lfs.github.com/spec/v1")


def is_git_lfs_pointer_file(path):
    try:
        with Path(path).open("rb") as handle:
            return is_git_lfs_pointer(handle.read(512))
    except OSError:
        return False


def git_blob_sha1(data):
    header = "blob {}\0".format(len(data)).encode("ascii")
    return hashlib.sha1(header + data).hexdigest()


def git_blob_sha1_file(path, size=None):
    path = Path(path)
    if size is None:
        size = path.stat().st_size
    digest = hashlib.sha1()
    digest.update("blob {}\0".format(size).encode("ascii"))
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def hash_stream(stream, size, collect=False):
    """Hash a blob stream without loading large optional files into memory."""
    sha1 = hashlib.sha1()
    sha256 = hashlib.sha256()
    header = "blob {}\0".format(size).encode("ascii")
    sha1.update(header)
    collected = bytearray() if collect else None
    for chunk in iter(lambda: stream.read(1024 * 1024), b""):
        sha1.update(chunk)
        sha256.update(chunk)
        if collected is not None:
            collected.extend(chunk)
    return sha1.hexdigest(), sha256.hexdigest(), bytes(collected) if collected is not None else None


def normalize_repository(value):
    """Return a canonical ``owner/name`` from common GitHub representations."""
    value = str(value or "").strip()
    if value.startswith("https://github.com/"):
        value = value[len("https://github.com/") :]
    if value.startswith("http://github.com/"):
        value = value[len("http://github.com/") :]
    value = value.rstrip("/")
    if value.endswith(".git"):
        value = value[:-4]
    return value


